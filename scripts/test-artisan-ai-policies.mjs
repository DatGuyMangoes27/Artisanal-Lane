// Isolated PostgreSQL only. Never points at production.
import {PGlite} from '../.codex/story-db-validation/node_modules/@electric-sql/pglite/dist/index.js';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const db=new PGlite();
const owner='10000000-0000-4000-8000-000000000001', other='10000000-0000-4000-8000-000000000002';
const shop='20000000-0000-4000-8000-000000000001', id='30000000-0000-4000-8000-000000000001';
let passed=0;
const ok=(name,value)=>{assert.ok(value,name);console.log('PASS '+name);passed++;};
const denied=async(name,sql)=>{let failed=false;try{await db.exec(sql);}catch{failed=true;}ok(name,failed);};
const role=async(name,user='')=>db.exec(`reset role;set role ${name};select set_config('test.uid','${user}',false);`);
const reserve=(request=id,user=owner,op='image',hash='a'.repeat(64))=>`select reserve_artisan_ai_request('${request}','${user}','${shop}','${op}','${hash}') as result`;
try {
 await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
 create schema auth;create schema storage;
 create table auth.users(id uuid primary key);
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
 create table public.shops(id uuid primary key,vendor_id uuid);
 create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
 create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text);
 create function storage.foldername(text) returns text[] language sql immutable as $$select string_to_array($1,'/')$$;
 alter table storage.objects enable row level security;
 create policy legacy_demo_storage on storage.objects for all using(true) with check(true);
 grant usage on schema auth,storage,public to anon,authenticated,service_role;
 grant select on public.shops to service_role;
 grant all on storage.objects to anon,authenticated,service_role;
 insert into auth.users values('${owner}'),('${other}');
 insert into shops values('${shop}','${owner}');`);
 await db.exec(readFileSync(new URL('../supabase/migrations/20260925083131_artisan_ai_requests.sql',import.meta.url),'utf8'));
 await role('anon');
 await denied('guest cannot read request ledger','select * from artisan_ai_requests');
 await denied('guest cannot reserve',reserve());
 await role('authenticated',owner);
 await denied('owner cannot call service reservation',reserve());
 await denied('owner cannot insert own fake result',`insert into artisan_ai_requests(id,user_id,shop_id,operation,payload_hash) values('${id}','${owner}','${shop}','image','${'a'.repeat(64)}')`);
 await role('service_role');
 await denied('server cannot reserve a foreign shop',reserve(id,other));
 ok('first request reserves',(await db.query(reserve())).rows[0].result.reserved);
 ok('same payload retry does not reserve again',!(await db.query(reserve())).rows[0].result.reserved);
 await denied('same ID cannot change payload',reserve(id,owner,'image','b'.repeat(64)));
 for(let n=2;n<=5;n++) await db.query(reserve('30000000-0000-4000-8000-00000000000'+n));
 await denied('sixth image hits per-user cap',reserve('30000000-0000-4000-8000-000000000006'));
 await db.exec(`update artisan_ai_requests set status='failed' where id='${id}'`);
 await denied('failed work still counts toward cap',reserve('30000000-0000-4000-8000-000000000006'));
 ok('listing has independent quota',(await db.query(reserve('30000000-0000-4000-8000-000000000006',owner,'listing'))).rows[0].result.reserved);
 await db.exec(`insert into storage.objects(bucket_id,name) values('artisan-ai-results','${owner}/result.png'),('existing-bucket','public.png')`);
 await role('authenticated',other);
 ok('another user cannot read ledger',(await db.query('select * from artisan_ai_requests')).rows.length===0);
 ok('legacy policy cannot expose private result',(await db.query("select * from storage.objects where bucket_id='artisan-ai-results'")).rows.length===0);
 await role('authenticated',owner);
 ok('owner can read their history',(await db.query('select * from artisan_ai_requests')).rows.length===6);
 ok('owner can read generated image',(await db.query("select * from storage.objects where bucket_id='artisan-ai-results'")).rows.length===1);
 await denied('owner cannot forge generated image',`insert into storage.objects(bucket_id,name) values('artisan-ai-results','${owner}/forged.png')`);
 ok('owner cannot overwrite result',(await db.query("update storage.objects set name='changed' where bucket_id='artisan-ai-results' returning id")).rows.length===0);
 ok('owner cannot delete result through broad policy',(await db.query("delete from storage.objects where bucket_id='artisan-ai-results' returning id")).rows.length===0);
 await role('anon');
 ok('guest cannot view private result',(await db.query("select * from storage.objects where bucket_id='artisan-ai-results'")).rows.length===0);
 ok('unrelated bucket access preserved',(await db.query("select * from storage.objects where bucket_id='existing-bucket'")).rows.length===1);
 console.log(`${passed} AI policy assertions passed.`);
} catch(error) {console.error(error.message);process.exitCode=1;} finally {await db.close();}
